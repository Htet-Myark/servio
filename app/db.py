TABLES = ["approvals", "journal", "kb_articles", "records", "catalog_items", "group_members",
          "groups", "users", "counters"]


def reset_db() -> None:
    """Drop all Servio tables and re-create them with demo data."""
    with transaction() as con:
        for table in TABLES:
            con.execute(f"DROP TABLE IF EXISTS {table} CASCADE")
    init_db()


