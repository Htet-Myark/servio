def now() -> datetime:
    return datetime.now(timezone.utc).replace(microsecond=0)


def iso(dt: datetime | None) -> str | None:
    # Fixed precision so ISO strings compare correctly in SQL.
    return dt.replace(microsecond=0).isoformat() if dt else None


def connect():
    return _PgConnection(_pg_pool().getconn())


# ---------------------------------------------------------------- connection pool

_pool = None


def _pg_pool():
    global _pool
    if _pool is None:
        if not DATABASE_URL:
            raise RuntimeError("DATABASE_URL is not set. Put your Supabase connection string "
                               "in .env (see .env.example).")

        def configure(conn):
            conn.execute(f"CREATE SCHEMA IF NOT EXISTS {PG_SCHEMA}")
            conn.execute(f"SET search_path TO {PG_SCHEMA}")
            conn.commit()

        # prepare_threshold=None keeps it working behind transaction-mode poolers too.
        _pool = ConnectionPool(DATABASE_URL, min_size=1, max_size=5, open=True,
                               kwargs={"prepare_threshold": None}, configure=configure,
                               check=ConnectionPool.check_connection)
    return _pool


def _pg_sql(sql: str) -> str:
    """? placeholders -> %s (and literal % -> %%), outside string literals only."""
    parts = sql.split("'")
    for i in range(0, len(parts), 2):  # even parts are outside string literals
        parts[i] = parts[i].replace("%", "%%").replace("?", "%s")
    return "'".join(parts)


def close_pool() -> None:
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


class Row:
    """A result row: index by position or column name, and dict(row) works."""
    __slots__ = ("_keys", "_values")

    def __init__(self, keys, values):
        self._keys, self._values = keys, values

    def keys(self):
        return list(self._keys)

    def __getitem__(self, key):
        if isinstance(key, str):
            return self._values[self._keys.index(key)]
        return self._values[key]

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def __repr__(self):
        return f"Row({dict(zip(self._keys, self._values))!r})"


def _row_factory(cursor):
    keys = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: Row(keys, values)


class _PgConnection:
    """A pooled psycopg connection with a small execute/commit/close API."""

    def __init__(self, conn):
        self._conn = conn
        conn.row_factory = _row_factory

    def execute(self, sql, params=()):
        return self._conn.execute(_pg_sql(sql), tuple(params))

    def executemany(self, sql, seq):
        with self._conn.cursor() as cur:
            cur.executemany(_pg_sql(sql), [tuple(p) for p in seq])

    def executescript(self, sql):
        self._conn.execute(sql)

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        if self._conn is not None:
            _pg_pool().putconn(self._conn)
            self._conn = None


@contextmanager
def transaction():
    con = connect()
    try:
        yield con
        con.commit()
    except Exception:
        con.rollback()
        raise
    finally:
        con.close()


def init_db() -> None:
    with transaction() as con:
        con.executescript(SCHEMA)
        if con.execute("SELECT COUNT(*) FROM users").fetchone()[0] == 0:
            seed(con)


